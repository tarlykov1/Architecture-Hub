import {test,expect} from '@playwright/test'

test.describe.configure({retries:0})

test('QA-WORK: compact editor gives more width to canvas and collapses/expands properties without losing flow selection',async({page})=>{
 await page.addInitScript(()=>sessionStorage.setItem('architecture-hub:access-token:session','browser-ci-development-token'))
 const api='http://127.0.0.1:8001',suffix=String(Date.now())
 const make=async(path:string,data:Record<string,unknown>)=>{
  const response=await page.request.post(api+path,{data})
  expect(response.status(),await response.text()).toBe(201)
  return (await response.json()).id as string
 }
 const system=await make('/api/objects',{name:'QA-WORK-CANVAS-'+suffix,kind:'system'})
 const source=await make('/api/infra',{system_id:system,name:'QA-WORK-CANVAS-source',kind:'vm'})
 const target=await make('/api/infra',{system_id:system,name:'QA-WORK-CANVAS-target',kind:'vm'})
 const flow=await make('/api/flows',{source_id:source,target_id:target,name:'QA-WORK-CANVAS-flow',protocol:'HTTPS'})
 await page.goto('/flows?system='+system)
 await page.getByRole('button',{name:'Редактор потоков',exact:true}).click()
 const board=page.getByRole('region',{name:'Редактор архитектурной схемы'})
 const stage=board.locator('.boardEditorStage')
 const rail=board.getByRole('toolbar',{name:'Инструменты архитектуры'})
 await expect(stage).toBeVisible()
 const railBox=await rail.boundingBox()
 expect(railBox?.width).toBeLessThanOrEqual(67)
 await rail.getByRole('button',{name:'→ Поток'}).click()
 const dock=board.getByRole('complementary',{name:'Свойства и изменения схемы'})
 await expect(dock).toBeVisible()
 const dockBox=await dock.boundingBox()
 expect(dockBox?.width).toBeLessThanOrEqual(272)
 await expect(dock.getByText('Начните стрелку от любой точки')).toHaveCount(0)
 const picker=dock.getByRole('combobox',{name:'Выбрать поток на схеме'})
 await picker.selectOption(flow)
 const canvas=board.locator('.boardCanvas')
 const before=await canvas.boundingBox()
 expect(before?.width).toBeGreaterThan(270)
 await dock.getByRole('button',{name:'Свернуть панель свойств'}).click()
 await expect(stage).toHaveClass(/boardDockCollapsed/)
 await expect(dock.getByRole('combobox',{name:'Выбрать поток на схеме'})).toBeHidden()
 await expect.poll(async()=> (await canvas.boundingBox())?.width||0).toBeGreaterThan((before?.width||0)+150)
 const collapsed=await dock.boundingBox()
 expect(collapsed?.width).toBeLessThanOrEqual(38)
 await dock.getByRole('button',{name:'Развернуть панель свойств'}).click()
 await expect(stage).not.toHaveClass(/boardDockCollapsed/)
 await expect(picker).toHaveValue(flow)
 await expect(dock.getByRole('combobox',{name:'Получатель выбранного потока'})).toHaveValue(target)
})
