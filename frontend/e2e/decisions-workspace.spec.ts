import {test, expect} from '@playwright/test'

test('QA-WORK: create a proposed VM, reopen the decision and submit it to its services', async ({page,request})=>{
  const title='QA-WORK-Решение-'+Date.now()
  const system=await request.post('http://127.0.0.1:8001/api/objects',{data:{kind:'system',name:title}})
  expect(system.status()).toBe(201)
  const {id}=await system.json()
  await page.addInitScript(()=>sessionStorage.setItem('architecture-hub:access-token:session','browser-ci-development-token'))
  await page.goto('/decisions')
  await page.getByRole('button',{name:'Создать решение',exact:true}).click()
  await page.getByLabel('Название',{exact:true}).fill(title)
  await page.getByLabel('Информационная система',{exact:true}).selectOption(id)
  await page.getByRole('button',{name:'Создать черновик'}).click()
  await page.getByRole('button',{name:'＋ ВМ'}).click()
  await page.getByLabel('Название ВМ').fill('QA-WORK-Новая ВМ')
  await page.getByRole('button',{name:'Добавить в черновик'}).click()
  await expect(page.locator('.decisionCanvas .react-flow__node')).toContainText('QA-WORK-Новая ВМ')
  await page.reload()
  await page.getByRole('button',{name:title,exact:true}).click()
  const inspector=page.getByRole('complementary',{name:'Карточка технического решения'})
  await expect(inspector).toContainText('QA-WORK-Новая ВМ')
  await inspector.getByRole('button',{name:'На согласование',exact:true}).click()
  await expect(page.locator('tr.current .decisionStatus')).toHaveText('На согласовании')
  await inspector.getByRole('button',{name:'Согласование',exact:true}).click()
  await expect(inspector).toContainText('Информационная безопасность')
  await expect(inspector).toContainText('На рассмотрении')
  await expect(inspector.getByRole('button',{name:'Согласовать',exact:true})).toHaveCount(0)
})

test('QA-WORK: withdraw, draw and edit a proposed flow from a registered VM',async({page,request})=>{
  const base='http://127.0.0.1:8001/api'
  const title='QA-WORK-Поток-'+Date.now()
  const system=await request.post(base+'/objects',{data:{kind:'system',name:title}})
  const systemId=(await system.json()).id
  const registered=await request.post(base+'/infra',{data:{kind:'vm',name:'QA-WORK-Источник',system_id:systemId}})
  const source=(await registered.json()).id
  const decision=await request.post(base+'/technical-decisions',{data:{title,system_id:systemId}})
  const row=await decision.json(),target=crypto.randomUUID()
  const url=base+'/technical-decisions/'+row.id
  const vm={id:target,system_id:systemId,name:'QA-WORK-OpenSearch',kind:'vm',x:400,y:0}
  const draft=await request.put(url,{data:{title,proposed_vms:[vm],expected_revision:row.revision}})
  expect(draft.ok()).toBeTruthy()
  const review=await request.post(url+'/submit',{data:{expected_revision:(await draft.json()).revision}})
  expect(review.ok()).toBeTruthy()
  await page.addInitScript(()=>sessionStorage.setItem('architecture-hub:access-token:session','browser-ci-development-token'))
  await page.goto('/decisions')
  await page.getByRole('button',{name:title,exact:true}).click()
  await page.getByRole('button',{name:'Открыть схему'}).click()
  await expect(page.getByRole('toolbar',{name:'Инструменты решения'})).toHaveCount(0)
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Отозвать в черновик'}).click()
  await expect(page.getByRole('toolbar',{name:'Инструменты решения'})).toBeVisible()
  const port=(id:string,anchor:string)=>page.locator(`.decisionCanvas [data-id="${id}"] [data-handleid="${anchor}"]`)
  const start=port(source,'out-right-1'),end=port(target,'out-left-2')
  await expect(start).toBeVisible()
  const a=await start.boundingBox(),b=await end.boundingBox()
  if(!a||!b)throw new Error('Expected visible VM connection points')
  await page.mouse.move(a.x+a.width/2,a.y+a.height/2)
  await page.mouse.down()
  await page.mouse.move(b.x+b.width/2,b.y+b.height/2,{steps:18})
  await page.mouse.up()
  await expect(page.getByRole('combobox',{name:'Источник',exact:true})).toHaveValue(source)
  await expect(page.getByRole('combobox',{name:'Получатель',exact:true})).toHaveValue(target)
  await page.getByLabel('Название потока').fill('QA-WORK-Журнал')
  await page.getByLabel('Протокол',{exact:true}).fill('HTTPS')
  await page.getByLabel('Порт',{exact:true}).fill('443')
  await page.getByRole('button',{name:'Добавить в черновик'}).click()
  const inspector=page.getByRole('complementary',{name:'Карточка технического решения'})
  await expect(inspector).toContainText('HTTPS 443')
  const saved=(await (await request.get(url)).json()).proposed_flows
  expect(saved).toHaveLength(1)
  expect(saved[0]).toMatchObject({source_id:source,target_id:target,source_handle:'out-right-1',target_handle:'in-left-2'})
  await page.reload()
  await page.getByRole('button',{name:title,exact:true}).click()
  await inspector.getByRole('button',{name:'QA-WORK-Журнал'}).click()
  await page.getByRole('button',{name:'Поменять направление'}).click()
  await page.getByRole('button',{name:'Сохранить поток'}).click()
  await expect(inspector).toContainText('QA-WORK-OpenSearch → QA-WORK-Источник')
  await inspector.getByRole('button',{name:'На согласование',exact:true}).click()
  await expect(page.locator('.decisionDrawing .decisionStatus')).toHaveText('На согласовании')
  const stored=await (await request.get(url)).json()
  expect(stored.proposed_flows).toHaveLength(1)
  expect(stored.proposed_flows[0]).toMatchObject({id:saved[0].id,source_id:target,target_id:source,protocol:'HTTPS',port:'443'})
})
