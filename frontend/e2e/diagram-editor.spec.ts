test('every VM exposes eight bidirectional connection points and reciprocal flows take distinct paths',async({page})=>{
  const systemId=await seedSystem(page)
  const components=await (await page.request.get('http://127.0.0.1:8001/api/infra')).json()
  const [a,b]=components.filter((x:{system_id:string})=>x.system_id===systemId)
  for(const [source,target] of [[a,b],[b,a]]){
    const result=await page.request.post('http://127.0.0.1:8001/api/flows',{
      data:{source_id:source.id,target_id:target.id,name:source.name+' to '+target.name,protocol:'HTTPS',port:'443'}
    })
    expect(result.status(),await result.text()).toBe(201)
  }
  await page.goto('/')
  await page.getByRole('navigation',{name:'Разделы архитектуры'}).getByRole('button',{name:'Компоненты',exact:true}).click()
  await page.getByRole('group',{name:'Представление компонентов'}).getByRole('button',{name:'Схема',exact:true}).click()
  await page.getByRole('button',{name:'Редактировать схему'}).click()
  await page.getByRole('combobox',{name:'Выбрать ИС для редактора компонентов'}).selectOption(systemId)
  const editor=page.getByRole('region',{name:'Редактор архитектурной схемы'})
  for(const label of ['Editor source','Editor destination']){
    const node=editor.locator('.react-flow__node-architectureComponent').filter({hasText:label})
    await expect(node.locator('.boardComponentPort')).toHaveCount(8)
    const ids=await node.locator('.boardComponentPort').evaluateAll(elements=>elements.map(element=>element.getAttribute('data-handleid')))
    expect(new Set(ids).size).toBe(8)
    expect(ids).toContain('left-a')
    expect(ids).toContain('right-b')
    expect(ids).toContain('bottom-a')
    expect(ids).toContain('top-b')
  }
  const paths=editor.locator('.react-flow__edge-path')
  await expect(paths).toHaveCount(2)
  const d=await paths.evaluateAll(elements=>elements.map(element=>element.getAttribute('d')))
  expect(d.every(Boolean)).toBe(true)
  expect(new Set(d).size).toBe(2)
  await expect(editor.locator('.reciprocalEdgeLabel')).toHaveCount(2)
})

