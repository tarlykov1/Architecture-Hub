test('existing flow has quick on-line actions, full reviewed card and direction reversal',async({page})=>{
  const id=await seedSystem(page)
  const all=await (await page.request.get('http://127.0.0.1:8001/api/infra')).json()
  const [src,dst]=all.filter((item:{system_id:string})=>item.system_id===id)
  const created=await page.request.post('http://127.0.0.1:8001/api/flows',{
    data:{source_id:src.id,target_id:dst.id,name:'Editable path',protocol:'TCP',port:'443',
      security:'unknown',schedule:'',data_description:''}
  })
  expect(created.status(),await created.text()).toBe(201)
  const flow=await created.json()
  await page.goto('/')
  await page.getByRole('navigation',{name:'Разделы архитектуры'}).getByRole('button',{name:'Компоненты',exact:true}).click()
  await page.getByRole('group',{name:'Представление компонентов'}).getByRole('button',{name:'Схема',exact:true}).click()
  await page.getByRole('button',{name:'Редактировать схему'}).click()
  await page.getByRole('combobox',{name:'Выбрать ИС для редактора компонентов'}).selectOption(id)
  const editor=page.getByRole('region',{name:'Редактор архитектурной схемы'})
  const clickFlow=async()=>{
    const line=editor.locator('.react-flow__edge-path').first()
    await expect(line).toBeVisible()
    const point=await line.evaluate(element=>{
      const path=element as SVGPathElement
      const matrix=path.getScreenCTM()
      if(!matrix)throw Error('Cannot locate flow path')
      const p=path.getPointAtLength(path.getTotalLength()/2).matrixTransform(matrix)
      return {x:p.x,y:p.y}
    })
    await page.mouse.click(point.x,point.y)
  }
  await clickFlow()
  const popover=editor.getByRole('dialog',{name:'Быстрое редактирование потока'})
  await expect(popover).toBeVisible()
  await expect(popover).toContainText('Editor source')
  await popover.getByRole('button',{name:'Полная карточка потока'}).click()
  const card=editor.getByRole('region',{name:'Полная карточка потока'})
  await expect(card).toBeVisible()
  await card.getByRole('textbox',{name:'Название потока'}).fill('Updated via board')
  await card.getByRole('combobox',{name:'Протокол потока'}).selectOption('HTTPS')
  await card.getByRole('combobox',{name:'Порт потока'}).selectOption('__new__')
  await card.getByRole('textbox',{name:'Новый порт потока'}).fill('9443')
  await card.getByRole('combobox',{name:'Защита потока'}).selectOption('TLS')
  await card.getByRole('button',{name:'Добавить изменения в черновик'}).click()
  await editor.getByRole('toolbar',{name:'Инструменты архитектуры'}).getByRole('button',{name:'Сохранить изменения'}).click()
  await editor.getByRole('textbox',{name:'Причина изменений'}).fill('Update protocol and technical security via editor')
  await editor.getByRole('button',{name:'Проверить изменения (1)'}).click()
  await page.getByRole('dialog',{name:'Подтверждение изменений архитектуры'}).getByRole('button',{name:'Подтвердить и записать в журнал'}).click()
  await expect(editor.getByText('Изменения и расположение схемы сохранены.')).toBeVisible()
  const saved=(await (await page.request.get('http://127.0.0.1:8001/api/flows')).json()).find((item:{id:string})=>item.id===flow.id)
  expect(saved.protocol).toBe('HTTPS')
  expect(saved.port).toBe('9443')
  expect(saved.security).toBe('TLS')
  expect(saved.name).toBe('Updated via board')
  await clickFlow()
  await expect(popover).toBeVisible()
  await popover.getByRole('button',{name:'⇄ Поменять направление'}).click()
  await editor.getByRole('toolbar',{name:'Инструменты архитектуры'}).getByRole('button',{name:'Сохранить изменения'}).click()
  await editor.getByRole('textbox',{name:'Причина изменений'}).fill('Reverse flow direction after approved change')
  await editor.getByRole('button',{name:'Проверить изменения (1)'}).click()
  await page.getByRole('dialog',{name:'Подтверждение изменений архитектуры'}).getByRole('button',{name:'Подтвердить и записать в журнал'}).click()
  const reversed=(await (await page.request.get('http://127.0.0.1:8001/api/flows')).json()).find((item:{id:string})=>item.id===flow.id)
  expect(reversed.source_id).toBe(dst.id)
  expect(reversed.target_id).toBe(src.id)
  expect(reversed.id).toBe(flow.id)
})
